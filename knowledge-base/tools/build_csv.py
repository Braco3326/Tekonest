"""Generate equipment.csv, manuals-missing.md and stats.json from equipment/*.json.

Stdlib only. Run from repo root:  python knowledge-base/tools/build_csv.py
Generated files are outputs; edit the JSON, never the CSV.
"""
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

KB = Path(__file__).resolve().parent.parent
EQUIP = KB / "equipment"
SPEC_KEYS = ["key_specs.polar_pattern", "key_specs.frequency_response", "connectors",
             "key_specs.phantom_power", "key_specs.sample_rates", "key_specs.channels", "key_specs.power"]


def two_source_keys(d):
    n = Counter()
    for s in d.get("sources", []):
        if s.get("confidence") == "unverified":
            continue
        for c in set(s.get("covers", [])):
            n[c] += 1
    return sorted(k for k, v in n.items() if v >= 2)


def has_official_manual(d):
    return d.get("manual_url", "not found") != "not found" and any(m.get("official") for m in d.get("manuals", []))


def main():
    rows, missing, nf_logs = [], [], []
    stats = {"per_category": defaultdict(lambda: Counter()), "per_file": {}, "totals": Counter()}
    for p in sorted(EQUIP.glob("*.json")):
        data = json.loads(p.read_text(encoding="utf-8"))
        stats["per_file"][p.name] = len(data.get("devices", []))
        for e in data.get("not_found_log", []):
            nf_logs.append((p.name, e))
        for d in data.get("devices", []):
            tsk = two_source_keys(d)
            official = has_official_manual(d)
            cat = d.get("category")
            c = stats["per_category"][cat]
            c["devices"] += 1
            c["official_manual"] += official
            c["two_source_any"] += bool(tsk)
            c["conflicts"] += len(d.get("conflicts", []))
            c["primary_source"] += any(s.get("confidence") == "verified-primary" for s in d.get("sources", []))
            c["french_manual"] += any(str(m.get("language", "")).startswith("fr") for m in d.get("manuals", []))
            c["in_catalog"] += bool(d.get("tekpractice", {}).get("in_catalog"))
            if not official:
                missing.append((p.name, d))
            tp = d.get("tekpractice", {})
            rows.append({
                "id": d.get("id"), "brand": d.get("brand"), "model": d.get("model"),
                "category": cat, "sub_type": d.get("sub_type"), "technology": d.get("technology"),
                "year_introduced": d.get("year_introduced"), "status": d.get("status"),
                "typical_uses": "; ".join(d.get("typical_uses", [])),
                "key_specs": json.dumps(d.get("key_specs", {}), ensure_ascii=False),
                "connectors": "; ".join(f"{c.get('connector')}({c.get('role')})" for c in d.get("connectors", [])),
                "signal_types": "; ".join(d.get("signal_types", [])),
                "manual_url": d.get("manual_url"), "datasheet_url": d.get("datasheet_url"),
                "product_page_url": d.get("product_page_url"),
                "manual_languages": "; ".join(d.get("manual_languages", [])),
                "source_count": len(d.get("sources", [])),
                "primary_sources": sum(s.get("confidence") == "verified-primary" for s in d.get("sources", [])),
                "two_source_fields": "; ".join(tsk),
                "conflicts": len(d.get("conflicts", [])),
                "in_tekpractice_catalog": tp.get("in_catalog", False),
                "tekpractice_catalog_id": tp.get("catalog_id") or "",
                "tekpractice_sim_value": tp.get("sim_value", ""),
                "file": p.name,
            })
    with (KB / "equipment.csv").open("w", encoding="utf-8-sig", newline="") as f:
        if rows:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)

    lines = ["# Missing official manuals", "",
             "Generated by `tools/build_csv.py`. Lists devices with no official manufacturer manual found, followed by each research agent's not-found log.", "",
             f"**{len(missing)} of {len(rows)} devices** have no official manual link.", "",
             "| Device id | Brand | Model | File | Datasheet found? |", "|---|---|---|---|---|"]
    for fname, d in missing:
        ds = "yes" if d.get("datasheet_url", "not found") != "not found" else "no"
        lines.append(f"| `{d.get('id')}` | {d.get('brand')} | {d.get('model')} | {fname} | {ds} |")
    lines += ["", "## Not-found log (all agents)", "", "| File | Device | What | Where searched |", "|---|---|---|---|"]
    for fname, e in nf_logs:
        lines.append(f"| {fname} | `{e.get('device_id', '')}` | {e.get('what', '')} | {str(e.get('searched', '')).replace('|', '/')} |")
    (KB / "manuals-missing.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    stats["totals"]["devices"] = len(rows)
    stats["totals"]["official_manual"] = sum(c["official_manual"] for c in stats["per_category"].values())
    stats["totals"]["two_source_any"] = sum(c["two_source_any"] for c in stats["per_category"].values())
    stats["totals"]["conflicts"] = sum(c["conflicts"] for c in stats["per_category"].values())
    stats["totals"]["primary_source"] = sum(c["primary_source"] for c in stats["per_category"].values())
    stats["totals"]["french_manual"] = sum(c["french_manual"] for c in stats["per_category"].values())
    out = {"per_category": {k: dict(v) for k, v in stats["per_category"].items()},
           "per_file": stats["per_file"], "totals": dict(stats["totals"])}
    (KB / "tools" / "stats.json").write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(out["totals"]))


if __name__ == "__main__":
    main()
