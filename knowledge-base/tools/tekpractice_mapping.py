"""Cross-reference tekpractice-sim/content/catalog.json with equipment/*.json.

Stdlib only. Run from repo root:  python knowledge-base/tools/tekpractice_mapping.py
Writes equipment/tekpractice-mapping.generated.md (tables only). The hand-written analysis
lives in equipment/tekpractice-mapping.md and links to the generated tables.
Reads catalog.json; never writes it.
"""
import json
from collections import Counter, defaultdict
from pathlib import Path

KB = Path(__file__).resolve().parent.parent
ROOT = KB.parent
CATALOG = ROOT / "tekpractice-sim" / "content" / "catalog.json"


def main():
    cat = json.loads(CATALOG.read_text(encoding="utf-8"))
    cat_ids = [d["id"] for d in cat["devices"]]
    cat_conns = {c["id"] for c in cat["connectorTypes"]}
    cat_sigs = {s["id"] for s in cat["signalTypes"]}

    devices = []
    for p in sorted((KB / "equipment").glob("*.json")):
        devices += json.loads(p.read_text(encoding="utf-8"))["devices"]
    by_id = {d["id"]: d for d in devices}

    conn_use, sig_use = Counter(), Counter()
    conn_devs, sig_devs = defaultdict(list), defaultdict(list)
    proposed_free = Counter()
    for d in devices:
        for c in {c["connector"] for c in d.get("connectors", [])}:
            if c not in cat_conns:
                conn_use[c] += 1
                conn_devs[c].append(d["id"])
        for s in set(d.get("signal_types", [])):
            if s not in cat_sigs:
                sig_use[s] += 1
                sig_devs[s].append(d["id"])
        tp = d.get("tekpractice", {})
        for x in tp.get("proposed_new_connectors", []) + tp.get("proposed_new_signals", []):
            proposed_free[x] += 1

    out = ["# TekPractice mapping — generated tables", "",
           "Generated by `tools/tekpractice_mapping.py` from `tekpractice-sim/content/catalog.json` (read-only) and `equipment/*.json`. Do not hand-edit.", "",
           "## 1. Catalog devices found in the knowledge base", "",
           "| Catalog id | In KB? | KB category / sub_type | Official manual | Sources (primary) |", "|---|---|---|---|---|"]
    for cid in cat_ids:
        d = by_id.get(cid)
        if d:
            prim = sum(s.get("confidence") == "verified-primary" for s in d["sources"])
            man = "yes" if d.get("manual_url", "not found") != "not found" else "no"
            out.append(f"| `{cid}` | yes | {d['category']} / {d['sub_type']} | {man} | {len(d['sources'])} ({prim}) |")
        else:
            out.append(f"| `{cid}` | **no** | — | — | — |")

    out += ["", "## 2. High-value candidates not yet in the catalog (sim_value = high)", "",
            "| KB id | Brand / model | Sub-type | Why (agent note) | Uses connectors/signals missing from catalog |", "|---|---|---|---|---|"]
    for d in sorted(devices, key=lambda x: (x["category"], x["id"])):
        tp = d.get("tekpractice", {})
        if tp.get("sim_value") == "high" and not tp.get("in_catalog"):
            missing = sorted({c["connector"] for c in d.get("connectors", []) if c["connector"] not in cat_conns} |
                             {s for s in d.get("signal_types", []) if s not in cat_sigs})
            reason = str(tp.get("sim_value_reason", "")).replace("|", "/")
            out.append(f"| `{d['id']}` | {d['brand']} {d['model']} | {d['category']} / {d['sub_type']} | {reason} | {', '.join(missing) or '—'} |")

    out += ["", "## 3. Connector ids used in the KB but missing from the catalog", "",
            "| Connector id | # devices | Example devices |", "|---|---|---|"]
    for c, n in conn_use.most_common():
        out.append(f"| `{c}` | {n} | {', '.join(conn_devs[c][:5])} |")
    out += ["", "## 4. Signal ids used in the KB but missing from the catalog", "",
            "| Signal id | # devices | Example devices |", "|---|---|---|"]
    for s, n in sig_use.most_common():
        out.append(f"| `{s}` | {n} | {', '.join(sig_devs[s][:5])} |")
    out += ["", "## 5. Free-text proposals from research agents (`tekpractice.proposed_new_*`)", "",
            "Not yet in taxonomy.json; review before adopting.", "", "| Proposal | # devices |", "|---|---|"]
    for x, n in proposed_free.most_common():
        out.append(f"| `{x}` | {n} |")
    (KB / "equipment" / "tekpractice-mapping.generated.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    found = sum(1 for c in cat_ids if c in by_id)
    print(f"catalog devices in KB: {found}/{len(cat_ids)}; missing connectors {len(conn_use)}, signals {len(sig_use)}")


if __name__ == "__main__":
    main()
