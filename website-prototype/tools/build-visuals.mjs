#!/usr/bin/env node
// Bundle the panel code (visuals/lib/*.js and the hero bootstrap) into one script for the home page.
// Usage: node tools/build-visuals.mjs   (writes assets/js/panel.js)
import { readFileSync } from "node:fs";
import { writeIfChanged } from "./write-if-changed.mjs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const VISUALS = resolve(HERE, "..", "..", "visuals");
const OUT = resolve(HERE, "..", "assets", "js", "panel.js");
const SOURCES = ["lib/damas.js", "lib/nest.js", "lib/panel.js", "hero-panel.js"];

/** The bundle text: a header line, then the four sources in order, separated by a lone semicolon. */
export function bundle() {
  const parts = SOURCES.map((f) => readFileSync(join(VISUALS, f), "utf8").replace(/\r\n/g, "\n").trimEnd());
  return "/* Generated by tools/build-visuals.mjs from visuals/. Do not edit. */\n" + parts.join("\n;\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeIfChanged(OUT, bundle());
  console.log(`wrote ${OUT}`);
}
