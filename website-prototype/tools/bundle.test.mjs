import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { bundle } from "./build-visuals.mjs";

const ASSETS = fileURLToPath(new URL("../assets/js/", import.meta.url));
const norm = (text) => text.replace(/\r\n/g, "\n");

test("the bundle holds the four sources in order", () => {
  const text = bundle(), lines = text.split("\n");
  assert.equal(lines[0], "/* Generated by tools/build-visuals.mjs from visuals/. Do not edit. */");
  const marks = ["g.Damas = ", "g.Nest = ", "g.Panel = ", "figure.hero-panel"].map((m) => text.indexOf(m));
  assert.ok(marks.every((p) => p > 0), `a source is missing: ${marks}`);
  assert.deepEqual(marks, [...marks].sort((a, b) => a - b), "sources are out of order");
});

test("the committed bundle is current", () => {
  assert.equal(norm(readFileSync(ASSETS + "panel.js", "utf8")), bundle(), "assets/js/panel.js is stale: run node tools/build-visuals.mjs");
});

test("the bundle is within the script budget", () => {
  const kb = (gzipSync(readFileSync(ASSETS + "panel.js")).length + gzipSync(readFileSync(ASSETS + "site.js")).length) / 1024;
  console.log(`# home page script: ${kb.toFixed(1)} KB gzip (limit 25)`);
  assert.ok(kb <= 25, `${kb.toFixed(1)} KB gzip`);
});

test("the bootstrap never starts under reduced motion or Save-Data", () => {
  const src = readFileSync(new URL("../../visuals/hero-panel.js", import.meta.url), "utf8");
  assert.match(src, /prefers-reduced-motion: reduce/);
  assert.match(src, /saveData/);
});

test("the bundle adds no globals and does nothing without a hero figure", () => {
  const sandbox = { window: {}, document: { querySelector: () => null }, navigator: {} };
  const before = Object.keys(sandbox).sort();
  vm.createContext(sandbox);
  vm.runInContext(bundle(), sandbox);
  assert.deepEqual(Object.keys(sandbox).sort(), before, "a top-level name leaked into the global scope");
  assert.equal(typeof sandbox.window.Panel.build, "function");
});
