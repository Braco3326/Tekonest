/**
 * betaBadges: which beta-modelled proposals have a VERIFIED size (Wave 1b finding 3).
 *
 * A beta-modelled device (a Bêta proposal that ships a 3D model) used to say « Bêta — dimensions estimées » for all of them, but 12 of the 23 have a
 * datasheet or dealer size with `sizeConfidence: ok` (all three axes): only their PORTS are undocumented. Those say « Bêta — connecteurs non vérifiés »;
 * the badge « dimensions estimées » stays for a size that is an estimate, partial, axis-assumed or in conflict.
 *
 * The runtime cannot read the 360 KB plan, so the ids are DERIVED from the plan here and written to `src/creation/betaBadges.json` by `npm run register`
 * (`--check` fails when the file is stale, a test holds the same). A beta-modelled id not in the file keeps « dimensions estimées »: the safe default.
 */
import { effectiveQuality, type PlanRow } from './equipmentPlan'

/** The ids of the beta-modelled rows whose size is verified (datasheet or dealer, three axes, sizeConfidence ok), sorted by code point. */
export function betaSizeVerifiedIds(rows: readonly PlanRow[]): string[] {
  return rows
    .filter((r) => r.betaModelled === true)
    .filter((r) => {
      const q = effectiveQuality(r.dataQuality, r.sizeMm, r.sizeConfidence)
      return q === 'datasheet' || q === 'dealer'
    })
    .map((r) => r.id)
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
}

/** The text of src/creation/betaBadges.json for these rows. */
export function renderBetaBadges(rows: readonly PlanRow[]): string {
  return JSON.stringify({ _comment: 'Generated by `npm run register` from content/proposals/equipment-plan.json: do not edit by hand. sizeVerified = beta-modelled proposals whose size is a datasheet or dealer size with all three axes and sizeConfidence ok (only their connectors are unverified).', sizeVerified: betaSizeVerifiedIds(rows) }, null, 1) + '\n'
}
