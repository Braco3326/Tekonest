/**
 * The outer size of every catalogue device that has an asset spec, for the cables' support surface (mission 3 A, « gravity first »): a cable that
 * crosses a device resting on the floor goes OVER it, on its top. Width (w), height (h) and depth (d) in millimetres, copied from the device's own
 * asset spec (content/asset-specs/<id>.json, `realSizeMm`, the size its 3D model is built and gated to; the spec's `sources` list holds the
 * manufacturer sheets). One number, one place: a device with no spec, or a spec without all three axes, is NOT in the file, and a cable treats it
 * as no support at all (it is never given an invented height).
 *
 * The file is compact (`[w, h, d]` per id); the source of every row is `content/asset-specs/<id>.json`.
 * `npm run sizes:cables` writes src/scene/cableSupportSizes.json; tests/scene/cableSupportSizes.test.ts fails when the file and the specs disagree.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export interface SupportSizeFile {
  note: string
  /** deviceId -> [w, h, d] in millimetres, read from content/asset-specs/<deviceId>.json realSizeMm. */
  devices: Record<string, [number, number, number]>
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const SUPPORT_SIZES_PATH = join(ROOT, 'src', 'scene', 'cableSupportSizes.json')

const axis = (v: unknown): v is number => typeof v === 'number' && Number.isFinite(v) && v > 0

export function deriveSupportSizes(root = ROOT): SupportSizeFile {
  const catalog = JSON.parse(readFileSync(join(root, 'content', 'catalog.json'), 'utf8')) as { devices: { id: string }[] }
  const devices: SupportSizeFile['devices'] = {}
  for (const { id } of catalog.devices) {
    const path = join(root, 'content', 'asset-specs', `${id}.json`)
    if (!existsSync(path)) continue
    const s = (JSON.parse(readFileSync(path, 'utf8')) as { realSizeMm?: { w?: unknown; h?: unknown; d?: unknown } }).realSizeMm
    if (!s || !axis(s.w) || !axis(s.h) || !axis(s.d)) continue
    devices[id] = [s.w, s.h, s.d]
  }
  return {
    note: 'Generated by tools/cable-support-sizes.ts from content/asset-specs/<id>.json realSizeMm ([w, h, d] in mm; the source of each row is its own asset spec). Do not edit: run npm run sizes:cables.',
    devices,
  }
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const file = deriveSupportSizes()
  writeFileSync(SUPPORT_SIZES_PATH, JSON.stringify(file) + '\n')
  console.log(`cable support sizes: ${Object.keys(file.devices).length} devices written to src/scene/cableSupportSizes.json`)
}
