/**
 * brandsRegister: generates the device table of docs/legal/BRANDS_AND_CREDITS.md section 6 from the asset manifest and the asset specs
 * (Wave 0, Task 0.6; spec 4.8). `npm run register` rewrites the block between the markers; `npm run register -- --check` fails when the
 * committed document differs from what the manifest and specs say, so the register cannot drift (a test holds the same).
 *
 * One row per manifest row of kind `device`: the device (label from the catalogue, else from the Bêta proposals, else its id), `tool` (how the GLB
 * was made), the manifest `source` text, the source of its dimensions (Wave 0b: ALWAYS an http(s) URL or the literal « catalogue (ours) », never a local file
 * path: the first source of the equipment plan row, else the manifest `specSource`, else the first source of its spec, each only when it is an http(s) URL;
 * a device with none of them says « catalogue (ours) »: its numbers are ours), the picture
 * origin, whether Meshy took part, and the trademark flag. Picture origin and Meshy are derived from the manifest's own fields, except for the
 * facts only a person knows (`KNOWN`).
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { renderBetaBadges } from './betaBadges'
import { loadPlan } from './equipmentPlan'
import { isMainModule } from './assets3d/mainModule'
import type { ManifestEntry } from './assets3d/manifest'

export type RegisterAsset = ManifestEntry
export interface LooseSpec {
  id: string
  sources?: { url?: string }[]
}

export const BEGIN = '<!-- register:begin (generated by `npm run register` from public/assets/ASSET_MANIFEST.json and content/asset-specs: do not edit by hand) -->'
export const END = '<!-- register:end -->'

/** Facts the manifest cannot say. The K12.2 shape is ours; its rear picture is a Meshy render, the front and side are official renders. */
const KNOWN: Readonly<Record<string, { picture?: string; meshy?: string }>> = {
  'qsc-k12-2': { picture: 'official front and side renders; rear = Meshy render', meshy: 'yes: rear picture only' },
}

/** A deterministic order: plain UTF-16 code-unit comparison, the same on every Node / ICU build (localeCompare is not: RØDE moved between builds). */
export const codePointCompare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0)

const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')

function pictureOf(a: RegisterAsset): string {
  const known = KNOWN[a.id]?.picture
  if (known) return known
  const src = a.source ?? ''
  if (a.tool === 'meshy') return 'Meshy model and its texture (from manufacturer photos)'
  if (/generic artwork/i.test(src)) return 'generic artwork drawn by us'
  if (/official photo/i.test(src)) return `official manufacturer photos (${(a.photos ?? []).join(', ') || 'see manifest'})`
  if (/Meshy render/i.test(src)) return `official photos and a Meshy render (${(a.photos ?? []).join(', ') || 'see manifest'})`
  if (src === 'modeled' || a.tool === 'scripted') return 'none (flat colours)'
  return 'see manifest'
}

const meshyOf = (a: RegisterAsset): string => {
  const known = KNOWN[a.id]?.meshy
  if (known) return known
  if (a.tool === 'meshy') return 'yes: geometry and picture'
  if (/Meshy render/i.test(a.source ?? '')) return 'yes: a picture'
  return 'no'
}

/** What the Dimensions source cell says for a device whose size has no web source (the 25 devices measured by hand, the power strip, the loom). */
export const OURS = 'catalogue (ours)'

const httpUrl = (u: string | undefined): string | undefined => (u !== undefined && /^https?:\/\/\S+$/.test(u) ? u : undefined)

/** The Dimensions source cell of a device: an http(s) URL or OURS, never a file path (a test holds it). */
export function dimensionsSource(a: RegisterAsset, spec: LooseSpec | undefined, planSource: string | undefined): string {
  return httpUrl(planSource) ?? httpUrl(a.specSource) ?? httpUrl(spec?.sources?.[0]?.url) ?? OURS
}

/** The text of section 6's generated part (everything between the markers). `planSources` is the first source URL of each equipment-plan row, by id. */
export function renderRegister(
  manifest: { assets: readonly RegisterAsset[] },
  specs: readonly LooseSpec[],
  labels: ReadonlyMap<string, string>,
  planSources: ReadonlyMap<string, string> = new Map(),
): string {
  const specById = new Map(specs.map((s) => [s.id, s]))
  const rows = manifest.assets
    .filter((a) => a.kind === 'device')
    .map((a) => {
      const label = labels.get(a.id) ?? a.id
      const dim = dimensionsSource(a, specById.get(a.id), planSources.get(a.id))
      return { label, id: a.id, line: `| ${cell(label)} (\`${a.id}\`) | ${cell(a.tool ?? 'unknown')} | ${cell(a.source ?? '—')} | ${cell(dim)} | ${cell(pictureOf(a))} | ${cell(meshyOf(a))} | ${cell(a.trademark ?? '—')} |`, meshy: meshyOf(a).startsWith('yes') }
    })
    .sort((x, y) => codePointCompare(x.label.toLowerCase(), y.label.toLowerCase()) || codePointCompare(x.label, y.label) || codePointCompare(x.id, y.id))
  const meshy = rows.filter((r) => r.meshy).map((r) => `\`${r.id}\``)
  return [
    `Generated from the manifest and the asset specs: ${rows.length} device rows; Meshy took part in ${meshy.length === 0 ? 'none' : `${meshy.length} (${meshy.join(', ')})`}.`,
    '',
    '| Device | tool | source (manifest) | Dimensions source | Picture origin | Meshy | trademark |',
    '|---|---|---|---|---|---|---|',
    ...rows.map((r) => r.line),
  ].join('\n')
}

/** `doc` with the text between the markers replaced by `block`. Throws when the markers are missing, repeated or out of order. */
export function replaceBlock(doc: string, block: string): string {
  const a = doc.indexOf(BEGIN)
  const b = doc.indexOf(END)
  if (a < 0 || b < 0 || b < a || doc.indexOf(BEGIN, a + 1) >= 0 || doc.indexOf(END, b + 1) >= 0)
    throw new Error('BRANDS_AND_CREDITS.md: the register markers are missing, repeated or out of order')
  return `${doc.slice(0, a + BEGIN.length)}\n${block}\n${doc.slice(b)}`
}

/** Labels of every device the pipeline can ship: the catalogue's, then the Bêta proposals' (a beta-modelled model). The catalogue wins. */
export function deviceLabels(catalog: { devices: { id: string; label: string }[] }, proposals?: { devices?: { id: string; label: string }[] } | null): Map<string, string> {
  const m = new Map<string, string>()
  for (const d of proposals?.devices ?? []) m.set(d.id, d.label)
  for (const d of catalog.devices) m.set(d.id, d.label)
  return m
}

/** The specs as loosely as the register needs them (id and sources only): an unfinished skeleton must not stop the register. */
export function readSpecsLoose(dir: string): LooseSpec[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => {
      const raw = readFileSync(join(dir, f), 'utf8').trim()
      return raw ? (JSON.parse(raw) as LooseSpec) : { id: f.slice(0, -5) }
    })
}

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function main(argv: string[]): number {
  const check = argv.includes('--check')
  const docPath = join(ROOT, 'docs', 'legal', 'BRANDS_AND_CREDITS.md')
  const manifest = JSON.parse(readFileSync(join(ROOT, 'public', 'assets', 'ASSET_MANIFEST.json'), 'utf8').replace(/^\uFEFF/, '')) as { assets: RegisterAsset[] }
  const catalog = JSON.parse(readFileSync(join(ROOT, 'content', 'catalog.json'), 'utf8')) as { devices: { id: string; label: string }[] }
  const proposalsPath = join(ROOT, 'content', 'proposals', 'catalog-proposals.json')
  const proposals = existsSync(proposalsPath) ? (JSON.parse(readFileSync(proposalsPath, 'utf8')) as { devices: { id: string; label: string }[] }) : null
  const planSources = new Map(loadPlan().flatMap((r) => (r.sources[0] ? [[r.id, r.sources[0]] as [string, string]] : [])))
  const block = renderRegister(manifest, readSpecsLoose(join(ROOT, 'content', 'asset-specs')), deviceLabels(catalog, proposals), planSources)
  const doc = readFileSync(docPath, 'utf8')
  const next = replaceBlock(doc, block)
  // the badge file the inventory reads (derived from the plan, Wave 1b finding 3)
  const badgesPath = join(ROOT, 'src', 'creation', 'betaBadges.json')
  const badges = renderBetaBadges(loadPlan())
  const badgesNow = existsSync(badgesPath) ? readFileSync(badgesPath, 'utf8') : ''
  if (next === doc && badges === badgesNow) {
    console.log('register: docs/legal/BRANDS_AND_CREDITS.md and src/creation/betaBadges.json are up to date')
    return 0
  }
  if (check) {
    console.error('register: docs/legal/BRANDS_AND_CREDITS.md or src/creation/betaBadges.json differs from the manifest, specs and plan: run `npm run register`')
    return 1
  }
  if (next !== doc) writeFileSync(docPath, next)
  if (badges !== badgesNow) writeFileSync(badgesPath, badges)
  console.log('register: updated')
  return 0
}

if (isMainModule(process.argv[1], import.meta.url)) process.exit(main(process.argv.slice(2)))
