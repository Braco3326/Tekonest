/**
 * Build content/kb-sheets.json — the inventory's short device sheets (ADR-0010
 * Décision 8) — from the sourced knowledge base (../knowledge-base/equipment).
 * Content layer only: catalog.json stays the source of truth for gameplay; this
 * file only adds read-only facts (key specs, connectors, official manual link)
 * and the taxonomy category used to group the inventory.
 *
 *   npx tsx tools/build-kb-sheets.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import type { KbSheet } from '../src/ui/inventoryModel'

/** KB connectors are objects ({ connector, role, count, … }) or, in older files, plain ids. */
type KbConnector = string | { connector?: string; id?: string; role?: string; count?: number; [extra: string]: unknown }

export interface KbDevice {
  id: string
  brand: string
  model: string
  category: string
  sub_type: string
  key_specs: Record<string, unknown>
  connectors: KbConnector[]
  manual_url: string
  product_page_url: string
  manual_languages: string[]
  tekpractice?: { in_catalog?: boolean; catalog_id?: string | null }
}

const MAX_SPECS = 6
const url = (v: string): string | null => (/^https?:\/\//.test(v) ? v : null)
const specText = (v: unknown): string =>
  Array.isArray(v) ? v.join(', ') : typeof v === 'object' && v ? JSON.stringify(v) : String(v)

function connectorText(c: KbConnector): string {
  if (typeof c === 'string') return c
  const name = c.connector ?? c.id ?? '?'
  const count = c.count && c.count > 1 ? ` ×${c.count}` : ''
  return c.role ? `${name}${count} — ${c.role}` : `${name}${count}`
}

export function toSheet(d: Omit<KbDevice, 'tekpractice'>): KbSheet {
  return {
    kbId: d.id,
    brand: d.brand,
    model: d.model,
    category: d.category,
    subType: d.sub_type,
    keySpecs: Object.entries(d.key_specs ?? {})
      .filter(([, v]) => v !== 'not found' && v !== null && v !== '')
      .slice(0, MAX_SPECS)
      .map(([k, v]) => [k.replace(/_/g, ' '), specText(v)]),
    connectors: (d.connectors ?? []).map(connectorText),
    manualUrl: url(d.manual_url),
    productUrl: url(d.product_page_url),
    manualLanguages: d.manual_languages ?? [],
  }
}

function main(): void {
  const root = resolve(__dirname, '..')
  const kb = resolve(root, '..', 'knowledge-base')
  const catalog = JSON.parse(readFileSync(join(root, 'content', 'catalog.json'), 'utf8')) as { devices: { id: string }[] }
  const catalogIds = new Set(catalog.devices.map((d) => d.id))
  const taxonomy = JSON.parse(readFileSync(join(kb, 'taxonomy.json'), 'utf8')) as {
    categories: { id: string; name_fr: string }[]
  }

  const devices: Record<string, KbSheet> = {}
  for (const file of readdirSync(join(kb, 'equipment')).filter((f) => f.endsWith('.json'))) {
    const data = JSON.parse(readFileSync(join(kb, 'equipment', file), 'utf8')) as { devices: KbDevice[] }
    for (const d of data.devices) {
      const catalogId = d.tekpractice?.catalog_id ?? (catalogIds.has(d.id) ? d.id : null)
      if (catalogId && catalogIds.has(catalogId)) devices[catalogId] = toSheet(d)
    }
  }

  const out = {
    generated: new Date().toISOString().slice(0, 10),
    note: 'Generated by tools/build-kb-sheets.ts from knowledge-base/equipment — do not edit by hand.',
    categories: Object.fromEntries(taxonomy.categories.map((c) => [c.id, c.name_fr])),
    devices,
  }
  writeFileSync(join(root, 'content', 'kb-sheets.json'), JSON.stringify(out, null, 1) + '\n')
  const missing = [...catalogIds].filter((id) => !devices[id])
  console.log(`kb-sheets: ${Object.keys(devices).length}/${catalogIds.size} catalog devices have a KB sheet`)
  if (missing.length) console.log(`  no KB record: ${missing.join(', ')}`)
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('tools/build-kb-sheets.ts')) main()
