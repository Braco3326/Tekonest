/**
 * assets3d/manifest: records one built asset in public/assets/ASSET_MANIFEST.json.
 *
 * Same BOM-safe read as tools/blender/update-manifest.mjs (a leading U+FEFF is dropped), but stricter on write:
 *  - an existing entry (matched by id) is updated in place, its unknown fields are kept; a missing id is appended
 *    with `status: 'ok'` unless the entry says otherwise
 *  - the file is rewritten atomically (temp file in the same folder, then rename) as 2-space JSON plus a trailing newline
 *  - a file that is missing, is not valid JSON or has no `assets` array is refused and left untouched
 * The optional fields written by the 3D pipeline: tool, toolVersion, date, specSource, logosRemoved, photos, taskId,
 * tris, gates.
 * `logosRemoved` is true only when the founder shipped with --logos-removed (removing logos from a texture is manual).
 */
import { existsSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs'

export interface ManifestGate {
  gate: string
  ok: boolean
}

export interface ManifestEntry {
  id: string
  kind?: 'device' | 'connector'
  status?: string
  tris?: number
  ports?: number
  /** How the GLB was made: generated by Meshy, or a hand-made raw GLB. */
  tool?: 'meshy' | 'raw' | 'scripted' | 'hybrid'
  /** Where the content comes from (set by the pipeline; replaces the licence fields of a downloaded model). */
  source?: string
  license?: string
  trademark?: string
  /** The Meshy ai_model used (for example 'meshy-7.1'), or 'raw'. */
  toolVersion?: string
  /** ISO timestamp of the build. */
  date?: string
  /** First spec source url, or 'spec' when the spec lists none. */
  specSource?: string
  logosRemoved?: boolean
  /** File names (not paths) of the reference photos sent to Meshy, in order ([] for a raw GLB). */
  photos?: string[]
  /** The Meshy task id of the shipped attempt, or null for a raw GLB. */
  taskId?: string | null
  gates?: ManifestGate[]
  [extra: string]: unknown
}

interface Manifest {
  assets: Record<string, unknown>[]
  [key: string]: unknown
}

const stripBom = (text: string): string => (text.charCodeAt(0) === 0xfeff ? text.slice(1) : text)

/** Parses the manifest at `path`; throws a clear error for a missing file, bad JSON or a missing `assets` array. */
function readManifest(path: string): Manifest {
  if (!existsSync(path)) throw new Error(`asset manifest not found: ${path}`)
  let parsed: unknown
  try {
    parsed = JSON.parse(stripBom(readFileSync(path, 'utf8')))
  } catch {
    throw new Error(`asset manifest ${path} is not valid JSON; refusing to write it`)
  }
  const assets = (parsed as { assets?: unknown } | null)?.assets
  if (!Array.isArray(assets)) throw new Error(`asset manifest ${path} has no "assets" array; refusing to write it`)
  return parsed as Manifest
}

/** Throws, writing nothing, unless the manifest at `path` is one recordAsset can update (call it before paying for a build). */
export function assertManifestUsable(path: string): void {
  readManifest(path)
}

/**
 * Licence and attribution fields written by the old rigging scripts for a DOWNLOADED model (Sketchfab author, CC-BY text, ...). A model the 3D
 * pipeline builds replaces the file, so these would credit someone for work that is no longer in it: recordAsset drops them when the entry names a `tool`.
 */
const STALE_PROVENANCE = ['source', 'sourceUrl', 'author', 'license', 'attributionText', 'trademark', 'note']

/** Adds or updates the manifest entry of `entry.id`. Throws, writing nothing, when the file cannot be trusted. */
export function recordAsset(manifestPath: string, entry: ManifestEntry): void {
  const manifest = readManifest(manifestPath)
  const existing = manifest.assets.find((a) => a.id === entry.id)
  if (existing) {
    if (entry.tool !== undefined) for (const k of STALE_PROVENANCE) delete existing[k]
    Object.assign(existing, entry)
  }
  else manifest.assets.push({ status: 'ok', ...entry })

  const temp = `${manifestPath}.${process.pid}.tmp`
  try {
    writeFileSync(temp, JSON.stringify(manifest, null, 2) + '\n')
    renameSync(temp, manifestPath)
  } catch (e) {
    if (existsSync(temp)) unlinkSync(temp)
    throw e
  }
}
