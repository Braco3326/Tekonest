/**
 * The footprints of the 2D schema page (mission 2): width and depth in millimetres of every catalogue device, copied from its asset spec
 * (content/asset-specs/<id>.json, `realSizeMm`, the size the 3D model is built and gated to; the spec's `sources` list holds the manufacturer
 * sheets it was read from). One number, one place: the 2D page never estimates a size, it reads this file; a device missing here is drawn as a
 * labelled default box that says its size is unknown.
 *
 * `npm run footprints:plan2d` writes src/plan2d/footprints.json; tests/plan2d/symbols.test.ts fails when the file and the specs disagree.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export interface FootprintFile {
  note: string
  /** deviceId -> width (w) and depth (d) in millimetres, and the file the numbers come from. */
  devices: Record<string, { w: number; d: number; source: string }>
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const FOOTPRINTS_PATH = join(ROOT, 'src', 'plan2d', 'footprints.json')

export function deriveFootprints(root = ROOT): FootprintFile {
  const catalog = JSON.parse(readFileSync(join(root, 'content', 'catalog.json'), 'utf8')) as { devices: { id: string }[] }
  const devices: FootprintFile['devices'] = {}
  for (const { id } of catalog.devices) {
    const rel = `content/asset-specs/${id}.json`
    const path = join(root, rel)
    if (!existsSync(path)) continue
    const spec = JSON.parse(readFileSync(path, 'utf8')) as { realSizeMm?: { w?: number; d?: number } }
    const w = spec.realSizeMm?.w
    const d = spec.realSizeMm?.d
    if (typeof w !== 'number' || typeof d !== 'number' || !(w > 0) || !(d > 0)) continue
    devices[id] = { w, d, source: rel }
  }
  return {
    note: 'Generated by tools/plan2d-footprints.ts from content/asset-specs/<id>.json realSizeMm (w, d in mm). Do not edit: run npm run footprints:plan2d.',
    devices,
  }
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  writeFileSync(FOOTPRINTS_PATH, JSON.stringify(deriveFootprints(), null, 1) + '\n')
  console.log(`plan2d footprints: ${Object.keys(deriveFootprints().devices).length} devices written to src/plan2d/footprints.json`)
}
