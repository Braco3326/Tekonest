/**
 * Build content/coach/kb-chunks.json — the TEK Brain fiches the AI coach may
 * cite as [kb:<id>] (ADR-0006 + knowledge-base/tek-brain/AI_USAGE.md).
 * For each catalog rule R1–R8: its TEK Brain mirror rule(s), their concepts,
 * and the faults that point at the mirror — at most MAX_PER_RULE chunks.
 *
 *   npx tsx tools/build-coach-kb.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import type { KbPack } from '../src/ai/grounding'

const ROOT = resolve(__dirname, '..')
const TB = resolve(ROOT, '..', 'knowledge-base', 'tek-brain')
const MAX_PER_RULE = 6

interface Chunk {
  id: string
  kind: string
  ref: string
  title: string
  text: string
  source_urls: string[]
}
interface KbRule {
  id: string
  catalog_rule: string | null
  concept_ids: string[]
}

const readItems = <T>(folder: string): T[] =>
  readdirSync(join(TB, folder))
    .filter((f) => f.endsWith('.json'))
    .flatMap((f) => (JSON.parse(readFileSync(join(TB, folder, f), 'utf8')) as { items: T[] }).items)

const chunks = readFileSync(join(TB, 'index', 'chunks.jsonl'), 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((l) => JSON.parse(l) as Chunk)
const firstChunk = new Map<string, Chunk>() // "kind:ref" → first part of the record
for (const c of chunks) if (!firstChunk.has(`${c.kind}:${c.ref}`)) firstChunk.set(`${c.kind}:${c.ref}`, c)

const rules = readItems<KbRule>('rules')
const faults = readItems<{ id: string; rule_ids: string[] }>('faults')

const pack: KbPack & { generated: string; note: string } = {
  generated: new Date().toISOString().slice(0, 10),
  note: 'Generated by tools/build-coach-kb.ts from knowledge-base/tek-brain/index — do not edit by hand.',
  byRule: {},
  chunks: {},
}
for (const r of ['R1', 'R2', 'R3', 'R4', 'R5', 'R6', 'R7', 'R8']) {
  const mirrors = rules.filter((x) => x.catalog_rule === r)
  const wanted = [
    ...mirrors.map((m) => `rule:${m.id}`),
    ...mirrors.flatMap((m) => m.concept_ids.map((c) => `concept:${c}`)),
    ...faults.filter((f) => mirrors.some((m) => f.rule_ids.includes(m.id))).map((f) => `fault:${f.id}`),
  ]
  const ids: string[] = []
  for (const key of [...new Set(wanted)]) {
    const c = firstChunk.get(key)
    if (!c || ids.length >= MAX_PER_RULE) continue
    ids.push(c.id)
    pack.chunks[c.id] = { title: c.title, text: c.text, sourceUrls: c.source_urls }
  }
  pack.byRule[r] = ids
}
writeFileSync(join(ROOT, 'content', 'coach', 'kb-chunks.json'), JSON.stringify(pack, null, 1) + '\n')
console.log(
  `coach kb: ${Object.keys(pack.chunks).length} chunks — ` +
    Object.entries(pack.byRule)
      .map(([r, ids]) => `${r}:${ids.length}`)
      .join(' '),
)
