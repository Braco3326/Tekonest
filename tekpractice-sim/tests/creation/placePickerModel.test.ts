import { readFileSync, readdirSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import catalogJson from '../../content/catalog.json'
import { RoomFile } from '../../src/explore/roomSchema'
import { gridMove, placeCards, templateCards, WITH_GEAR_ROOMS, type PlaceCard } from '../../src/creation/shell/placePickerModel'
import { placeSummary, summarizeRoom } from '../../src/creation/placeSummary'
import summaryJson from '../../src/creation/placeSummary.json'

const DIR = 'content/rooms'
const rooms = readdirSync(DIR)
  .filter((f) => f.endsWith('.json') && f !== 'index.json')
  .map((f) => RoomFile.parse(JSON.parse(readFileSync(`${DIR}/${f}`, 'utf8'))))
const catalogIds = new Set((catalogJson as { devices: { id: string }[] }).devices.map((d) => d.id))
const SETS = [
  { envId: 'plateau', name: 'Plateau', floor: [24, 14] as [number, number] },
  { envId: 'radio', name: 'Radio', floor: [16, 10] as [number, number] },
  { envId: 'theatre', name: 'Théâtre', floor: [20, 16] as [number, number] },
]
const input = () => ({ rooms: placeSummary().rooms, sets: SETS })

describe('placeSummary (generated by tools/room-thumbs.ts) matches the room data', () => {
  it('one entry per room, dims L × l × h and the catalog-matched gear count', () => {
    expect(placeSummary().rooms).toHaveLength(32)
    for (const r of rooms) {
      const s = placeSummary().rooms.find((x) => x.id === r.id)
      expect(s, r.id).toEqual(summarizeRoom(r, catalogIds))
      expect(s!.dims).toEqual([r.dimensions_m.length.typical, r.dimensions_m.width.typical, r.dimensions_m.height.typical])
    }
    expect(summaryJson).toEqual(placeSummary())
  })
  it('gearNames: a KB display name (brand + model) for every room gear id the catalog lacks (review fix 4)', () => {
    const names = placeSummary().gearNames
    expect(names['dhd-rx2']).toBe('DHD audio RX2 (Series 52)')
    expect(names['telos-hx2']).toBe('Telos (Telos Alliance) Hx2')
    // only non-catalog ids that rooms actually use
    for (const id of Object.keys(names)) {
      expect(catalogIds.has(id), id).toBe(false)
      expect(rooms.some((r) => (r.gear_positions ?? []).some((g) => g.equipment_id === id)), id).toBe(true)
    }
  })
})

describe('placeCards (L1): 32 rooms + 3 sets + « Salle vide neutre »', () => {
  const cards = placeCards(input())
  it('36 cards with unique keys', () => {
    expect(cards).toHaveLength(36)
    expect(new Set(cards.map((c) => c.key)).size).toBe(36)
    expect(cards.filter((c) => c.key.startsWith('room:'))).toHaveLength(32)
    expect(cards.filter((c) => c.key.startsWith('set:')).map((c) => c.key)).toEqual(['set:plateau', 'set:radio', 'set:theatre'])
    expect(cards[0]).toMatchObject({ key: 'blank', title: 'Salle vide neutre', sizeLabel: '24 × 14 m', thumb: 'blank.svg' })
  })
  it('every card has a title, a size « L × l × h m », a type and a thumbnail named after it', () => {
    for (const c of cards) {
      expect(c.title, c.key).not.toBe('')
      expect(c.typeLabel, c.key).not.toBe('')
      expect(c.sizeLabel, c.key).toMatch(/^\d+(,\d+)?( × \d+(,\d+)?){1,2} m$/)
      expect(c.thumb, c.key).toMatch(/^[a-z0-9-]+\.svg$/)
    }
    const hall = cards.find((c) => c.key === 'room:concert-hall-medium')!
    expect(hall.sizeLabel).toBe('32 × 18,1 × 9 m') // French decimal comma
    expect(hall.thumb).toBe('concert-hall-medium.svg')
    expect(cards.find((c) => c.key === 'set:theatre')!.thumb).toBe('set-theatre.svg')
  })
  it('the « Avec le matériel » flag is on exactly the 5 rooms with the most catalog gear (L2)', () => {
    const ranked = rooms
      .map((r) => ({ id: r.id, n: (r.gear_positions ?? []).filter((g) => catalogIds.has(g.equipment_id)).length }))
      .sort((a, b) => b.n - a.n || a.id.localeCompare(b.id))
      .slice(0, 5)
      .map((r) => r.id)
    expect([...WITH_GEAR_ROOMS]).toEqual(ranked)
    const flagged = cards.filter((c) => c.withGear)
    expect(flagged.map((c) => c.key).sort()).toEqual(ranked.map((id) => `room:${id}`).sort())
    expect(cards.find((c) => c.key === 'room:radio-talk-studio-medium')!.withGearCount).toBe(9)
  })
})

describe('templateCards: the « Modèles » row', () => {
  const cards = placeCards(input())
  it('a template card shows its room, its device count, and its room thumbnail', () => {
    const [t] = templateCards([{ id: 'concert-simple-reference', name_fr: 'Concert simple (référence)', roomId: 'room:concert-hall-medium', devices: 4 }], cards)
    expect(t).toMatchObject<Partial<PlaceCard>>({
      key: 'template:concert-simple-reference',
      title: 'Concert simple (référence)',
      thumb: 'concert-hall-medium.svg',
      sizeLabel: '32 × 18,1 × 9 m',
      withGear: false,
      withGearCount: 4,
    })
  })
  it('a template whose room is not a place card is left out', () => {
    expect(templateCards([{ id: 'x', name_fr: 'X', roomId: 'room:nope', devices: 1 }], cards)).toEqual([])
  })
})

describe('gridMove (CA-13): arrows move the highlight, never leave the grid', () => {
  it('moves by one across, by a row up and down; Home / End', () => {
    expect(gridMove(0, 'ArrowRight', 36, 6)).toBe(1)
    expect(gridMove(1, 'ArrowLeft', 36, 6)).toBe(0)
    expect(gridMove(3, 'ArrowDown', 36, 6)).toBe(9)
    expect(gridMove(9, 'ArrowUp', 36, 6)).toBe(3)
    expect(gridMove(17, 'Home', 36, 6)).toBe(0)
    expect(gridMove(2, 'End', 36, 6)).toBe(35)
  })
  it('stops at the edges', () => {
    expect(gridMove(0, 'ArrowLeft', 36, 6)).toBe(0)
    expect(gridMove(35, 'ArrowRight', 36, 6)).toBe(35)
    expect(gridMove(2, 'ArrowUp', 36, 6)).toBe(2)
  })
  it('ArrowDown into a short last row lands on the last card', () => {
    expect(gridMove(29, 'ArrowDown', 34, 6)).toBe(33) // row 4 col 5 → row 5 has 4 cards
    expect(gridMove(33, 'ArrowDown', 34, 6)).toBe(33)
  })
  it('never leaves [0, count) for any key, index, count and column count', () => {
    const keys = ['ArrowLeft', 'ArrowRight', 'ArrowUp', 'ArrowDown', 'Home', 'End'] as const
    for (let count = 1; count <= 13; count++)
      for (let columns = 1; columns <= 7; columns++)
        for (let i = 0; i < count; i++)
          for (const k of keys) {
            const j = gridMove(i, k, count, columns)
            expect(j >= 0 && j < count, `${k} ${i}/${count} c${columns}`).toBe(true)
          }
  })
})
